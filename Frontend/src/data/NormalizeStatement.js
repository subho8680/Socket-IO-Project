export const formatProblemStatement = (text = "") => {
  if (!text) return "";

  return text
    .replace(/\\\\&/g, "&")
    .replace(/\\&/g, "&")
    .replace(/\\\\\|/g, "|")
    .replace(/\\\|/g, "|")
    .replace(/\\\\_/g, "_")
    .replace(/\\_/g, "_")
    .replace(/\\\\\^/g, "^")
    .replace(/\\\^/g, "^")
    .replace(/\\\\/g, "\\")

    .replace(/\\ldots|\\cdots|\\dots/g, "...")
    .replace(/\\leq|\\le/g, "≤")
    .replace(/\\geq|\\ge/g, "≥")
    .replace(/\\lt/g, "<")
    .replace(/\\gt/g, ">")
    .replace(/\\neq/g, "≠")
    .replace(/\\approx/g, "≈")
    .replace(/\\equiv/g, "≡")
    .replace(/\\pm/g, "±")
    .replace(/\\mp/g, "∓")
    .replace(/\\times/g, "×")
    .replace(/\\cdot/g, "·")
    .replace(/\\div/g, "÷")
    .replace(/\\sum/g, "∑")
    .replace(/\\prod/g, "∏")
    .replace(/\\infty/g, "∞")
    .replace(/\\partial/g, "∂")
    .replace(/\\nabla/g, "∇")
    .replace(/\\angle/g, "∠")
    .replace(/\\triangle/g, "△")
    .replace(/\\degree/g, "°")
    .replace(/\\in\b/g, "∈")
    .replace(/\\notin/g, "∉")
    .replace(/\\subseteq/g, "⊆")
    .replace(/\\subset/g, "⊂")
    .replace(/\\supseteq/g, "⊇")
    .replace(/\\cup/g, "∪")
    .replace(/\\cap/g, "∩")
    .replace(/\\forall/g, "∀")
    .replace(/\\exists/g, "∃")
    .replace(/\\mid/g, "|")
    .replace(/\\vert/g, "|")
    .replace(/\\rightarrow|\\to/g, "→")
    .replace(/\\Rightarrow/g, "⇒")
    .replace(/\\leftrightarrow/g, "↔")
    .replace(/\\sqrt/g, "√")
    .replace(/\\frac\{([^}]*)\}\{([^}]*)\}/g, "($1/$2)")

    .replace(/\\alpha/g, "α")
    .replace(/\\beta/g, "β")
    .replace(/\\gamma/g, "γ")
    .replace(/\\delta/g, "δ")
    .replace(/\\epsilon/g, "ε")
    .replace(/\\theta/g, "θ")
    .replace(/\\lambda/g, "λ")
    .replace(/\\mu/g, "μ")
    .replace(/\\pi/g, "π")
    .replace(/\\sigma/g, "σ")
    .replace(/\\phi/g, "φ")
    .replace(/\\omega/g, "ω")
    .replace(/\\rho/g, "ρ")

    .replace(/([a-zA-Z])_(\d+)/g, "$1<sub>$2</sub>")
    .replace(/([a-zA-Z])_([a-zA-Z])/g, "$1<sub>$2</sub>")
    .replace(/([a-zA-Z])(\d+)/g, "$1<sub>$2</sub>")

    .replace(/\^(\d+)/g, "<sup>$1</sup>")
    .replace(/\^([a-zA-Z]+)/g, "<sup>$1</sup>")

    .replace(/\)(\d+)/g, ")<sup>$1</sup>")

    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/&nbsp;/g, " ")
    .replace(/&le;/g, "≤")
    .replace(/&ge;/g, "≥")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")

    .replace(/[{}]/g, "")
    .replace(/\$/g, "")
    .replace(/\n/g, "<br/>")
    .replace(/\s{2,}/g, " ")
    .trim();
};
