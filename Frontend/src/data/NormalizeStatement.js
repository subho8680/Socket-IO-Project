export const formatProblemStatement = (text = "") => {
  if (!text) return "";

  return text
    .replace(/\\lt/g, "<")
    .replace(/\\gt/g, ">")
    .replace(/\\le/g, "≤")
    .replace(/\\ge/g, "≥")
    .replace(/\\neq/g, "≠")
    .replace(/\\approx/g, "≈")
    .replace(/\\equiv/g, "≡")
    .replace(/\\pm/g, "±")
    .replace(/\\mp/g, "∓")

    .replace(/\\times/g, "×")
    .replace(/\\cdot/g, "·")
    .replace(/\\div/g, "÷")
    .replace(/\\sum/g, "∑")
    .replace(/\\prod/g, "∏")
    .replace(/\\infty/g, "∞")
    .replace(/\\partial/g, "∂")
    .replace(/\\nabla/g, "∇")
    .replace(/\\angle/g, "∠")
    .replace(/\\triangle/g, "△")
    .replace(/\\degree/g, "°")

    .replace(/\\in\b/g, "∈")
    .replace(/\\notin/g, "∉")
    .replace(/\\subseteq/g, "⊆")
    .replace(/\\subset/g, "⊂")
    .replace(/\\supseteq/g, "⊇")
    .replace(/\\cup/g, "∪")
    .replace(/\\cap/g, "∩")
    .replace(/\\forall/g, "∀")
    .replace(/\\exists/g, "∃")
    .replace(/\\rightarrow/g, "→")
    .replace(/\\to\b/g, "→")
    .replace(/\\Rightarrow/g, "⇒")
    .replace(/\\leftrightarrow/g, "↔")

    .replace(/\\sqrt/g, "√")
    .replace(/\\frac\{([^}]*)\}\{([^}]*)\}/g, "($1/$2)")

    .replace(/\\alpha/g, "α")
    .replace(/\\beta/g, "β")
    .replace(/\\gamma/g, "γ")
    .replace(/\\delta/g, "δ")
    .replace(/\\epsilon/g, "ε")
    .replace(/\\theta/g, "θ")
    .replace(/\\lambda/g, "λ")
    .replace(/\\mu/g, "μ")
    .replace(/\\pi/g, "π")
    .replace(/\\sigma/g, "σ")
    .replace(/\\phi/g, "φ")
    .replace(/\\omega/g, "ω")
    .replace(/\\rho/g, "ρ")

    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/&nbsp;/g, " ")
    .replace(/&le;/g, "≤")
    .replace(/&ge;/g, "≥")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")

    .replace(/\b(a|x|y|i|j|k|n|m)(i|j|k|n|m)\b/g, "$1<sub>$2</sub>")
    .replace(/\b(a|x|y)(a|b|c|x|y)\b/g, "$1<sub>$2</sub>")
    .replace(/\b(a|x|y|i|j|k|n|m)(\d+)\b/g, "$1<sub>$2</sub>")

    .replace(/\)(\d+)/g, ")<sup>$1</sup>")
    .replace(/\^([a-zA-Z0-9]+)/g, "<sup>$1</sup>")
    .replace(/_([a-zA-Z0-9]+)/g, "<sub>$1</sub>")

    .replace(/[{}]/g, "")
    .replace(/\n/g, "<br/>")
    .replace(/\s{2,}/g, " ")
    .trim();
};